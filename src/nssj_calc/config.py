import tomllib
from dataclasses import dataclass
from enum import Enum
from pathlib import Path

from pydantic import BaseModel, ValidationError

from nssj_calc.utils import (
	DEFAULT_CONFIG,
)


@dataclass(frozen=True)
class PlanCost:
	"""`PlanCost` is used as the value of the generated `TrainingPlan` enum."""

	sessions: int
	price: float
	competition_validity: bool


class MinMax[T: (int, float)](BaseModel):
	"""`MinMax` used as a parent class by many container classes of the `config.toml` file."""

	min: T
	max: T


class Weight(MinMax[float]):
	"""`Weight` used for parsing the `config.toml` file. Container class for [validation.weight]."""


class Competitions(MinMax[int]):
	"""`Competitions` used for parsing the `config.toml` file. Container class for [validation.competitions]."""

	price: float


class Coaching(MinMax[int]):
	"""`Coaching` used for parsing the `config.toml` file. Container class for [validation.coaching]."""

	price: float


class TrainingPlanRaw(BaseModel):
	"""`TrainingPlanRaw` used for parsing the `config.toml` file. Container class for [training_plan].
	This is only a raw version of the actual enum. The real enum is dynamically generated by another fn."""

	name: str
	sessions: int
	price: float
	competition_validity: bool


class Validation(BaseModel):
	"""`Validation` used for parsing the `config.toml` file. Container class for [validation]."""

	weight: Weight = Weight(min=0.0, max=0.0)
	competitions: Competitions = Competitions(min=0, max=1, price=22.0)
	coaching: Coaching = Coaching(min=0, max=5, price=9.50)


class Config(BaseModel):
	"""`Config` used for parsing the `config.toml` file. Represents the entire config file."""

	validation: Validation = Validation()
	weight_categories: dict[str, float] = {}
	training_plan: list[TrainingPlanRaw] = []

	@classmethod
	def new(cls, path: str = "config.toml", _retried: bool = False) -> Config:
		"""Generates the `Config` Enum from `config.toml`.

		Args:
			path: The path to the `config.toml` file. Defaults to `config.toml` (exe dir).
			_retried: A simple boolean to fix looping forever. Defaults to False.

		Returns:
			An instance of Config, freshly generated from the `config.toml` file."""

		fpath: Path = Path(path)
		try:
			with fpath.open("rb") as file:
				config = tomllib.load(file)
		except FileNotFoundError:
			if _retried:
				raise
			_ = fpath.write_text(DEFAULT_CONFIG, "utf-8")
			return cls.new(path, _retried=True)

		try:
			config = cls.model_validate(config)
		except ValidationError:
			print(
				"config.toml has wrong types! Could not be validated. Using default config."
			)
			print("Delete the config.toml file to generate a new config.toml.")
			config = cls.model_validate(DEFAULT_CONFIG)

		if not config.weight_categories:
			raise ValueError(f"No [weight_categories] found in {fpath.resolve()}")

		return config


# Helpers to dynamically generate enumerated WeightCategory and
# TrainingPlan enums from the config.toml file.
def enumerate_weight_categories(CONFIG: Config):
	"""Generates the `WeightCategory` Enum from `config.toml`.

	Args:
		CONFIG: An instance of [`Config`], to calculate things.

	Returns:
		A type called "WeightCategory", which is an enum containing values."""
	return Enum("WeightCategory", CONFIG.weight_categories)


def enumerate_training_plans(CONFIG: Config):
	"""Generates the `TrainingPlan` Enum from `config.toml`.

	Args:
		CONFIG: An instance of [`Config`], to calculate things.

	Returns:
		A type called "TrainingPlan", which is an enum containing values."""
	plan = {
		i.name: PlanCost(i.sessions, i.price, i.competition_validity)
		for i in CONFIG.training_plan
	}

	return Enum("TrainingPlan", plan)


CONFIG = Config.new()
WeightCategory = enumerate_weight_categories(CONFIG)
TrainingPlan = enumerate_training_plans(CONFIG)
